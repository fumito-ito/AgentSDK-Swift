/// Represents a tool call, e.g. a function call or computer action call.
public final class ToolCallItem: RunItemImpl, @unchecked Sendable {
    /// Optional tool description if known at item creation time.
    public var description: String?
    /// Optional short display label if known at item creation time.
    public var title: String?
    /// Optional metadata describing the source of a function-tool-backed item.
    public var toolOrigin: ToolOrigin?
    /// SDK-resolved tool name when the provider payload does not carry one.
    var resolvedToolName: String?

    public init(agent: Agent, rawItem: JSONObject, description: String? = nil, title: String? = nil, toolOrigin: ToolOrigin? = nil) {
        self.description = description
        self.title = title
        self.toolOrigin = toolOrigin
        super.init(agent: agent, rawItem: rawItem)
    }

    public override var type: String { "tool_call_item" }

    /// The tool name from the raw item, if available.
    public var toolName: String? { resolvedToolName ?? rawItem.string("name") }

    /// The call identifier from the raw item, if available.
    public var callId: String? { rawItem.callIdOrId }
}

/// Represents the output of a tool call.
public final class ToolCallOutputItem: RunItemImpl, @unchecked Sendable {
    /// The output of the tool call: whatever the tool returned. `rawItem` contains the
    /// string representation sent to the model.
    public var output: any Sendable
    /// Optional metadata describing the source of a function-tool-backed item.
    public var toolOrigin: ToolOrigin?
    /// SDK-only custom data attached to this tool output. It is not sent back to the model.
    public var customData: JSONObject?

    public init(agent: Agent, rawItem: JSONObject, output: any Sendable, toolOrigin: ToolOrigin? = nil, customData: JSONObject? = nil) {
        self.output = output
        self.toolOrigin = toolOrigin
        self.customData = customData
        super.init(agent: agent, rawItem: rawItem)
    }

    public override var type: String { "tool_call_output_item" }

    /// The call identifier from the raw item, if available.
    public var callId: String? { rawItem.callIdOrId }

    /// Converts the tool output into an input item for the next model turn.
    ///
    /// Hosted tool outputs (e.g. shell) carry SDK bookkeeping fields that the Responses API does
    /// not accept, so they are stripped while keeping `rawItem` intact.
    public override func toInputItem() throws -> TResponseInputItem {
        var payload = rawItem
        if payload.type == "shell_call_output" {
            payload.removeValue(forKey: "status")
            payload.removeValue(forKey: "shell_output")
            payload.removeValue(forKey: "provider_data")
        }
        return outputItemToInputItem(payload)
    }
}

