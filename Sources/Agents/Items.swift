/// A tool call that requires approval before execution.
///
/// Equality is by identity so that distinct approvals stay separate.
public final class ToolApprovalItem: RunItemImpl, @unchecked Sendable {
    /// Tool name for approval tracking; falls back to the raw item's name.
    public var toolName: String?
    /// Optional Responses API namespace for function-tool approvals.
    public var toolNamespace: String?
    /// Optional metadata describing where the approved tool call came from.
    public var toolOrigin: ToolOrigin?
    /// Canonical function-tool lookup metadata when the approval targets a function tool.
    var toolLookupKey: FunctionToolLookupKey?
    /// Whether permanent approval decisions should also be recorded under the bare tool name.
    var allowBareNameAlias: Bool

    public init(
        agent: Agent,
        rawItem: JSONObject,
        toolName: String? = nil,
        toolNamespace: String? = nil,
        toolOrigin: ToolOrigin? = nil,
        toolLookupKey: FunctionToolLookupKey? = nil,
        allowBareNameAlias: Bool = false
    ) {
        self.toolName = toolName ?? rawItem.string("name")
        self.toolNamespace = toolNamespace ?? rawItem.string("namespace")
        self.toolOrigin = toolOrigin
        self.allowBareNameAlias = allowBareNameAlias
        if let toolLookupKey {
            self.toolLookupKey = toolLookupKey
        } else if rawItem.type == "function_call", let name = self.toolName,
                  self.toolNamespace == nil || self.toolNamespace != name {
            self.toolLookupKey = getFunctionToolLookupKey(name, self.toolNamespace)
        } else {
            self.toolLookupKey = nil
        }
        super.init(agent: agent, rawItem: rawItem)
    }

    public override var type: String { "tool_approval_item" }

    /// The tool name from `toolName` or the raw item.
    public var name: String? {
        if let toolName, !toolName.isEmpty { return toolName }
        return rawItem.string("name") ?? rawItem.string("tool_name")
    }

    /// A display-friendly tool name, collapsing synthetic deferred namespaces.
    public var qualifiedName: String? {
        guard let toolName else { return nil }
        return toolTraceName(toolName, namespace: toolNamespace) ?? toolName
    }

    /// Tool call arguments if present on the raw item.
    public var arguments: String? {
        let candidate = rawItem["arguments"] ?? rawItem["params"] ?? rawItem["input"]
        guard let candidate, !candidate.isNull else { return nil }
        if case .string(let string) = candidate { return string }
        return candidate.pythonJSONString()
    }

    /// The call identifier from the raw item.
    public var callId: String? { rawItem.callIdOrId }

    /// Approval items must never be sent as input.
    public override func toInputItem() throws -> TResponseInputItem {
        throw AgentsException(
            "ToolApprovalItem cannot be converted to an input item. These items should be filtered out before preparing input for the API."
        )
    }
}

extension ToolApprovalItem: Hashable {
    public static func == (lhs: ToolApprovalItem, rhs: ToolApprovalItem) -> Bool { lhs === rhs }
    public func hash(into hasher: inout Hasher) { hasher.combine(ObjectIdentifier(self)) }
}

/// A model response.
public struct ModelResponse: Sendable {
    /// A list of outputs (messages, tool calls, etc.) generated by the model.
    public var output: [TResponseOutputItem]
    /// The usage information for the response.
    public var usage: Usage
    /// An ID for the response which can be used to refer to it in subsequent calls to the model.
    public var responseId: String?
    /// The transport request ID for this model call, if provided.
    public var requestId: String?
    /// A JSON-compatible snapshot of the provider usage payload, when preservation is enabled.
    public var rawUsage: JSONObject?

    public init(output: [TResponseOutputItem], usage: Usage, responseId: String?, requestId: String? = nil, rawUsage: JSONObject? = nil) {
        self.output = output
        self.usage = usage
        self.responseId = responseId
        self.requestId = requestId
        self.rawUsage = rawUsage
    }

    /// Converts the output into a list of input items suitable for passing to the model.
    public func toInputItems() -> [TResponseInputItem] {
        output.map(outputItemToInputItem)
    }
}

/// Helpers for working with items.
public enum ItemHelpers {
    /// Extracts the last text content or refusal from a message.
    public static func extractLastContent(_ message: TResponseOutputItem) throws -> String {
        guard let message = ResponseOutputMessage(json: message), let last = message.content.last else { return "" }
        if let text = ResponseOutputText(json: last) { return text.text }
        if let refusal = ResponseOutputRefusal(json: last) { return refusal.refusal }
        throw ModelBehaviorError("Unexpected content type: \(last.type ?? "unknown")")
    }

    /// Extracts the last text content from a message, if any. Ignores refusals.
    public static func extractLastText(_ message: TResponseOutputItem) -> String? {
        guard let message = ResponseOutputMessage(json: message), let last = message.content.last else { return nil }
        return ResponseOutputText(json: last)?.text
    }

    /// Extracts all text content from a message, if any. Ignores refusals.
    public static func extractText(_ message: TResponseOutputItem) -> String? {
        guard let message = ResponseOutputMessage(json: message) else { return nil }
        let text = message.content.compactMap { ResponseOutputText(json: $0)?.text }.joined()
        return text.isEmpty ? nil : text
    }

    /// Extracts refusal content from a message, if any.
    public static func extractRefusal(_ message: TResponseOutputItem) -> String? {
        guard let message = ResponseOutputMessage(json: message) else { return nil }
        let refusal = message.content.compactMap { ResponseOutputRefusal(json: $0)?.refusal }.joined()
        return refusal.isEmpty ? nil : refusal
    }

    /// Converts a string or list of input items into a list of input items.
    public static func inputToNewInputList(_ input: RunInput) -> [TResponseInputItem] {
        switch input {
        case .text(let text): return [["content": .string(text), "role": "user"]]
        case .items(let items): return items
        }
    }

    /// Concatenates all the text content from a list of message output items.
    public static func textMessageOutputs(_ items: [RunItem]) -> String {
        items.compactMap { $0 as? MessageOutputItem }.map(textMessageOutput).joined()
    }

    /// Extracts all the text content from a single message output item.
    public static func textMessageOutput(_ message: MessageOutputItem) -> String {
        ResponseOutputMessage(json: message.rawItem)?.content.compactMap { ResponseOutputText(json: $0)?.text }.joined() ?? ""
    }

    /// Creates a tool call output item from a tool call and its output.
    ///
    /// Accepts plain values (stringified) or structured outputs (`ToolOutputText`,
    /// `ToolOutputImage`, `ToolOutputFileContent`, or arrays of them).
    public static func toolCallOutputItem(
        _ toolCall: ResponseFunctionToolCall,
        output: any Sendable,
        outputJSONSchema: JSONObject? = nil
    ) throws -> TResponseInputItem {
        let converted: JSONValue
        if outputJSONSchema != nil {
            let dumped: JSONValue
            if let string = output as? String {
                guard let parsed = try? JSONValue.parse(string) else {
                    throw UserError("Function tool output schema requires a JSON object.")
                }
                dumped = parsed
            } else {
                dumped = try jsonDump(output)
            }
            guard case .object(let object) = dumped else {
                throw UserError("Function tool output schema requires a JSON object.")
            }
            converted = .string(object.jsonString())
        } else if let string = output as? String {
            converted = .string(string)
        } else if isProgrammaticToolCall(toolCall.json) {
            if let structured = convertToolOutputAsStructured(output) {
                converted = structured
            } else {
                do {
                    converted = .string(try jsonDump(output).jsonString())
                } catch {
                    throw UserError(
                        "Programmatic function tool outputs must be strings, structured tool outputs, or JSON-serializable values."
                    )
                }
            }
        } else {
            converted = convertToolOutput(output)
        }
        var item: TResponseInputItem = [
            "call_id": .string(toolCall.callId),
            "output": converted,
            "type": "function_call_output",
        ]
        copyToolCallCaller(toolCall.json, into: &item)
        return item
    }

    /// Copies a program caller relationship from a tool call to its output item.
    public static func copyToolCallCaller(_ toolCall: JSONObject, into outputItem: inout JSONObject) {
        guard let caller = toolCall["caller"], !caller.isNull else { return }
        if case .object(let object) = caller {
            outputItem["caller"] = .object(object.filter { _, value in !value.isNull })
        } else {
            outputItem["caller"] = caller
        }
    }

    /// Converts a tool return value into an output acceptable by the Responses API.
    static func convertToolOutput(_ output: any Sendable) -> JSONValue {
        convertToolOutputAsStructured(output) ?? .string(stringify(output))
    }

    /// Converts known structured tool outputs without stringifying other values.
    static func convertToolOutputAsStructured(_ output: any Sendable) -> JSONValue? {
        if let list = output as? [any Sendable] {
            let converted = list.map(structuredFunctionOutput)
            guard !converted.isEmpty, converted.allSatisfy({ $0 != nil }) else { return nil }
            return .array(converted.compactMap { $0.map(JSONValue.object) })
        }
        if case .array(let list)? = output as? JSONValue {
            let converted = list.map(structuredFunctionOutput)
            guard !converted.isEmpty, converted.allSatisfy({ $0 != nil }) else { return nil }
            return .array(converted.compactMap { $0.map(JSONValue.object) })
        }
        return structuredFunctionOutput(output).map { .array([.object($0)]) }
    }

    static func structuredFunctionOutput(_ output: any Sendable) -> JSONObject? {
        switch output {
        case let text as ToolOutputText:
            return ["type": "input_text", "text": .string(text.text)]
        case let image as ToolOutputImage:
            var result: JSONObject = ["type": "input_image"]
            if let url = image.imageURL { result["image_url"] = .string(url) }
            if let fileId = image.fileId { result["file_id"] = .string(fileId) }
            if let detail = image.detail { result["detail"] = .string(detail) }
            return result
        case let file as ToolOutputFileContent:
            var result: JSONObject = ["type": "input_file"]
            if let data = file.fileData { result["file_data"] = .string(data) }
            if let url = file.fileURL { result["file_url"] = .string(url) }
            if let fileId = file.fileId { result["file_id"] = .string(fileId) }
            if let filename = file.filename { result["filename"] = .string(filename) }
            return result
        case let object as JSONObject:
            return structuredFromDict(object)
        case let value as JSONValue:
            if case .object(let object) = value { return structuredFromDict(object) }
            return nil
        default:
            return nil
        }
    }

    /// Validates a `{"type": ...}` dictionary as a structured tool output.
    private static func structuredFromDict(_ object: JSONObject) -> JSONObject? {
        switch object.string("type") {
        case "text":
            guard let text = object.string("text") else { return nil }
            return structuredFunctionOutput(ToolOutputText(text: text))
        case "image":
            guard let image = try? ToolOutputImage(
                imageURL: object.string("image_url"), fileId: object.string("file_id"), detail: object.string("detail")
            ) else { return nil }
            return structuredFunctionOutput(image)
        case "file":
            guard let file = try? ToolOutputFileContent(
                fileData: object.string("file_data"), fileURL: object.string("file_url"),
                fileId: object.string("file_id"), filename: object.string("filename")
            ) else { return nil }
            return structuredFunctionOutput(file)
        default:
            return nil
        }
    }
}

/// Converts an arbitrary tool output into JSON (pydantic `dump_python(mode="json")`).
func jsonDump(_ value: any Sendable) throws -> JSONValue {
    switch value {
    case let json as JSONValue: return json
    case let object as JSONObject: return .object(object)
    case let string as String: return .string(string)
    case let bool as Bool: return .bool(bool)
    case let int as Int: return .int(int)
    case let double as Double: return .double(double)
    case is Void: return .null
    case let list as [any Sendable]: return .array(try list.map(jsonDump))
    case let dictionary as [String: any Sendable]:
        return .object(JSONObject(try dictionary.mapValues(jsonDump)))
    case let encodable as any Encodable:
        return try JSONValue(encoding: encodable)
    default:
        throw TypeError("Object of type \(type(of: value)) is not JSON serializable")
    }
}

/// Renders a value like Python's `str(value)`.
func stringify(_ value: any Sendable) -> String {
    switch value {
    case let string as String: return string
    case let json as JSONValue:
        if case .string(let string) = json { return string }
        return json.pythonJSONString()
    case let object as JSONObject: return JSONValue.object(object).pythonJSONString()
    case is Void: return "None"
    case let bool as Bool: return bool ? "True" : "False"
    case let optional as OptionalProtocol where optional.isNone: return "None"
    default: return String(describing: value)
    }
}

/// Detects `nil` hidden behind `any Sendable`.
protocol OptionalProtocol {
    var isNone: Bool { get }
}

extension Optional: OptionalProtocol {
    var isNone: Bool { self == nil }
}
