import Foundation

/// The input to a run: a string or a list of Responses input items.
public enum RunInput: Sendable, Equatable {
    case text(String)
    case items([TResponseInputItem])

    /// The input as a list of items (a string becomes one user message).
    public var inputItems: [TResponseInputItem] {
        ItemHelpers.inputToNewInputList(self)
    }

    public var text: String? {
        if case .text(let text) = self { return text }
        return nil
    }

    /// Whether the input is an empty string or an empty list.
    public var isEmpty: Bool {
        switch self {
        case .text(let text): return text.isEmpty
        case .items(let items): return items.isEmpty
        }
    }
}

extension RunInput: ExpressibleByStringLiteral {
    public init(stringLiteral value: String) { self = .text(value) }
}

extension RunInput: ExpressibleByArrayLiteral {
    public init(arrayLiteral elements: TResponseInputItem...) { self = .items(elements) }
}

/// An item generated by an agent (upstream `RunItemBase` and the `RunItem` union).
///
/// Swift: upstream items are dataclasses checked with `isinstance`; here they are classes that
/// conform to this protocol. Check concrete types with `item as? ToolCallItem`.
public protocol RunItemBase: AnyObject, Sendable {
    /// The agent whose run caused this item to be generated.
    var agent: Agent { get }
    /// The raw Responses item from the run (an output item or an input item).
    var rawItem: JSONObject { get }
    /// The item type discriminator, e.g. `"message_output_item"`.
    var type: String { get }
    /// Converts this item into an input item suitable for passing to the model.
    func toInputItem() throws -> TResponseInputItem
}

/// An item generated by an agent.
public typealias RunItem = any RunItemBase

extension RunItemBase {
    public func toInputItem() throws -> TResponseInputItem {
        outputItemToInputItem(rawItem)
    }
}

/// Strips output-only tool_search fields before replaying items back to the API.
func toolSearchItemToInputItem(_ rawItem: JSONObject) -> TResponseInputItem {
    rawItem.removing("created_by")
}

/// Converts an output item into replayable input, stripping output-only metadata.
func outputItemToInputItem(_ rawItem: JSONObject) -> TResponseInputItem {
    if rawItem.type == "tool_search_call" || rawItem.type == "tool_search_output" {
        return toolSearchItemToInputItem(rawItem)
    }
    var payload = rawItem.removing("created_by")
    if rawItem.type == "shell_call_output", case .array(let chunks)? = payload["output"] {
        payload["output"] = .array(chunks.map { chunk in
            guard case .object(let object) = chunk else { return chunk }
            return .object(object.removing("created_by"))
        })
    }
    return payload
}

/// Base class for concrete run items.
open class RunItemImpl: RunItemBase, @unchecked Sendable {
    public let agent: Agent
    public var rawItem: JSONObject
    open var type: String { "" }

    public init(agent: Agent, rawItem: JSONObject) {
        self.agent = agent
        self.rawItem = rawItem
    }

    open func toInputItem() throws -> TResponseInputItem {
        outputItemToInputItem(rawItem)
    }
}

